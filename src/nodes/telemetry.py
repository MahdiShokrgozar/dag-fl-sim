# src/nodes/telemetry.py
import json
from typing import Dict, Any

class NodeTelemetry:
    """
    Handles performance tracking, network traffic counting, and metric snapshots for a node.
    
    network requires precise tracking of computational delays and communication overhead 
    across both Layer-1 (Global-DAG) and Layer-2 (Task-DAG/Settlement).
    This class isolates the monitoring logic from the core networking logic.
    """
    
    def __init__(self, node_ref: Any):
        """
        Initializes the telemetry tracker for a specific node.
        
        Args:
            node_ref (BaseNode): A reference to the parent node to access its state.
        """
        self.node = node_ref
        
        # --- Performance & Network Tracking ---
        self.cpu_utilization = 0.0
        self.metric_network_delay = 0.0
        self.metric_busy_time = 0.0
        self.metric_last_snapshot = 0.0
        # Simulation timestamp at which cpu_utilization was last recomputed, so
        # repeat snapshot_metrics() calls inside one tick reuse it instead of
        # each resetting the accounting window (see snapshot_metrics). -1.0
        # rather than 0.0 so the very first snapshot at t=0.0 still computes.
        self._utilization_computed_at = -1.0
        self.dropped_count = 0
        self.event_counters: Dict[str, int] = {}
        self.traffic_tracker = {"l1": 0, "l2": 0, "ipfs": 0, "total": 0}
        self.network_stats = {
            "l1_bytes_sent": 0, 
            "l2_bytes_sent": 0, 
            "storage_bytes_up": 0, 
            "msg_count": 0
        }
        self.sent_bytes = 0
        
        # --- Layer-2 Specific State ---
        self.l2_bytes_intra = 0
        self.l2_bytes_inter = 0
        self.l2_head_load = 0
        self.l2_head_queue_len = 0
        self.l2_worker_updates = 0
        self.l2_last_round_time = 0.0
        self.l2_cluster_stability = 0

    def register_traffic(self, size_bytes: int, channel: str = "l1") -> None:
        """
        Records outbound network traffic generated by the node.
        
        Args:
            size_bytes (int): The size of the payload in bytes.
            channel (str): The communication channel ('l1', 'l2', or 'ipfs').
        """
        self.traffic_tracker["total"] += size_bytes
        if channel in self.traffic_tracker:
            self.traffic_tracker[channel] += size_bytes
        
        if channel == "l1": 
            self.network_stats["l1_bytes_sent"] += size_bytes
        elif channel == "l2": 
            self.network_stats["l2_bytes_sent"] += size_bytes
        elif channel == "ipfs": 
            self.network_stats["storage_bytes_up"] += size_bytes
            
        self.sent_bytes += size_bytes

    def register_compute(self, duration: float) -> None:
        """
        Records the simulated computational time spent on tasks (e.g., training).
        
        Args:
            duration (float): Time spent in seconds.
        """
        self.metric_busy_time += duration

    def register_network_delay(self, duration: float) -> None:
        """
        Records asynchronous network delays not accounted for by standard DAG broadcasts 
        (e.g., uploading to IPFS or external data fetches).
        """
        self.metric_network_delay += duration
        
    def snapshot_metrics(self) -> Dict[str, Any]:
        """
        Captures a temporal snapshot of the node's operational state.
        This is polled periodically by the global MetricManager to generate CSV reports.
        
        Returns:
            Dict[str, Any]: A dictionary containing current metrics and node state.
        """
        # Calculate CPU utilization over the last snapshot interval.
        #
        # This is a DESTRUCTIVE read: it consumes `metric_busy_time` and advances
        # the window. Four separate collectors call it per reporting tick
        # (accuracy, performance, security, tip_selection - see
        # src/metrics/manager.py), and AccuracyMetric runs first. So the first
        # call computed the real figure and reset the window, and every later
        # call in the same tick saw time_delta == 0 and took the else branch.
        # PerformanceMetric - the one that actually publishes
        # `avg_cpu_utilization` - runs second, so that column was structurally
        # 0.0 in EVERY run this project has ever produced, for every protocol.
        # Confirmed in plan 24's crash check: 0.0 at every tick in all four
        # cells, including FARABI cells doing real training.
        #
        # That matters beyond tidiness: the paper's central claim is a COST
        # comparison (FARABI's ~0.05s per deep validation against IronForge's
        # ~0.375s PoL replay), and this is the column that was supposed to carry
        # it. Recomputing per unique simulation timestamp makes the read
        # idempotent within a tick, so collector count and ordering no longer
        # change the measurement.
        # See thesis-hub/docs/decisions.md, 2026-09-12.
        current_time = getattr(self.node.simulator, 'current_time', 0.0) if self.node.simulator else 0.0

        if current_time != self._utilization_computed_at:
            time_delta = current_time - self.metric_last_snapshot
            if time_delta > 0:
                raw_util = (self.metric_busy_time / time_delta) * 100.0
                self.cpu_utilization = min(100.0, raw_util)
            else:
                self.cpu_utilization = 0.0

            self.metric_busy_time = 0.0
            self.metric_last_snapshot = current_time
            self._utilization_computed_at = current_time
        # else: repeat call within the same tick - reuse the value just computed.

        # Track network congestion and dropped packets (due to limited queue capacity)
        current_queue = len(getattr(self.node, 'pending_updates', []))
        queue_capacity = getattr(self.node, 'queue_capacity', 100)
        
        if current_queue > queue_capacity:
            self.dropped_count += (current_queue - queue_capacity)
        
        traffic_total = sum([
            self.network_stats["l1_bytes_sent"], 
            self.network_stats["l2_bytes_sent"], 
            self.network_stats["storage_bytes_up"]
        ])
        
        
        # Fetch latest evaluation accuracy
        acc = self.node.node_accuracy if self.node.node_accuracy > 0 else getattr(self.node, 'last_accuracy', 0.0)

        # Safely serialize per-class accuracy for detailed CSV logging
        try:
            per_class_dict = getattr(self.node, 'per_class_accuracy', {})
            per_class_json = json.dumps({str(k): float(v) for k, v in per_class_dict.items()})
        except TypeError:
            per_class_json = "{}"

        # `node.is_slashed` is only ever written by the IronForge settlement path
        # (ironforge_settlement.py). FARABI penalises through the reputation
        # module's own quarantine set instead and never touches this attribute,
        # so it stays False forever for FARABI runs. Once a node is quarantined,
        # base_node.create_and_broadcast_block returns early and never trains or
        # re-evaluates again (see base_node.py) - its node_accuracy is frozen at
        # whatever it was at quarantine time. Without this check, is_active never
        # excludes it, so AccuracyMetric.aggregate keeps averaging in a stale,
        # frozen number forever.
        #
        # First attempt here asked the node's OWN reputation object about itself
        # (`self.node.reputation.is_quarantined(self.node.node_id)`). That is
        # wrong for exactly the nodes this fix exists for: a `lazy`/quarantined
        # node's own settlement loop is what would apply its own self-verdict,
        # and laziness means that loop runs rarely or not at all - verified on
        # 2026-09-07 (results/dual_selection/1_paradox/lazy_unified): node_11
        # was quarantined by every honest observer (7 `[QUARANTINE]` log lines,
        # each from a different node's own ledger) but `node_11.reputation.
        # is_quarantined('node_11')` stayed False the whole run, because node_11
        # itself never got around to processing the evidence against itself.
        # security.py's `SecurityMetric._peer_votes` already solved this the
        # correct way for its own is_slashed column on 2026-09-06 (thesis-hub/
        # docs/decisions.md, "باگ متریک"): ask every peer's ledger, not the
        # target's own, and require a quorum. That fix never reached this
        # shared telemetry snapshot (AccuracyMetric's own is_active exclusion
        # reads `stats.get("is_slashed")` from here, not from SecurityMetric's
        # column), so it's replicated here rather than imported, to avoid a
        # src/nodes -> src/metrics dependency inversion.
        is_quarantined_by_quorum = False
        simulator = getattr(self.node, 'simulator', None)
        peers = getattr(simulator, 'nodes', None) or {}
        if peers:
            peer_count = 0
            quarantine_votes = 0
            for peer in peers.values():
                peer_reputation = getattr(peer, 'reputation', None)
                if peer_reputation is None:
                    continue
                peer_count += 1
                checker = getattr(peer_reputation, 'is_quarantined', None)
                if callable(checker):
                    try:
                        if checker(self.node.node_id):
                            quarantine_votes += 1
                    except Exception:
                        pass
            if peer_count > 0:
                quorum = max(1, int(peer_count * 0.5))
                is_quarantined_by_quorum = quarantine_votes >= quorum
        is_slashed = bool(getattr(self.node, 'is_slashed', False)) or is_quarantined_by_quorum

        return {
            "node_id": self.node.node_id,
            "node_type": self.node.node_type,
            "is_malicious": self.node.is_malicious,
            "reputation_score": float(self.node.get_current_reputation() if hasattr(self.node, 'get_current_reputation') else 0.5),
            "is_slashed": is_slashed,
            "is_active": 0 if is_slashed else 1,
            "node_accuracy": float(acc),
            "per_class_acc_json": per_class_json,
            "per_class_accuracy": getattr(self.node, 'per_class_accuracy', {}),
            "node_cpu_virtual": self.cpu_utilization,
            "node_queue_len": current_queue,
            "node_dropped": self.dropped_count,
            "node_traffic_bytes": traffic_total,
            "l1_bytes": self.network_stats["l1_bytes_sent"],
            "l2_bytes": self.network_stats["l2_bytes_sent"],
            "ipfs_bytes": self.network_stats["storage_bytes_up"],
            "l2_session_id": getattr(self.node, 'l2_state', {}).get('active_session', "None"),
            "l2_role": getattr(self.node, 'l2_state', {}).get('role', "worker"),
            "l2_cluster_size": getattr(self.node, 'l2_cluster_size', 1),
            "l2_cluster_stability": self.l2_cluster_stability,
            "l2_bytes_intra": self.l2_bytes_intra,
            "l2_bytes_inter": self.l2_bytes_inter,
            "l2_head_load": self.l2_head_load,
            "l2_head_queue_len": self.l2_head_queue_len,
            "l2_worker_updates": self.l2_worker_updates,
            "l2_last_round_time": self.l2_last_round_time,
            "hardware_tier": getattr(self.node, "hardware_tier", "Standard Node"),
            "is_straggler": getattr(self.node, "is_straggler", False),
            "delay_multiplier": round(getattr(self.node, "delay_multiplier", 1.0), 3),
            "tips_filtered_finalized": self.event_counters.get("tip_filtered_finalized", 0),
            "tips_filtered_quarantined": self.event_counters.get("tip_filtered_quarantined", 0),
            "tips_filtered_slash_confirmed": self.event_counters.get("tip_filtered_slash_confirmed", 0),
            "tips_filtered_slashed": self.event_counters.get("tip_filtered_slashed", 0),
            "no_valid_tips_after_filter": self.event_counters.get("no_valid_tips_after_filter", 0),

        }
        
    def log_event(self, event_type: str, metadata: Dict[str, Any] = None) -> None:
        """
        Registers a protocol event for metric reporting.
        These events are aggregated and reported in CSV metrics.
        """
        self.event_counters[event_type] = self.event_counters.get(event_type, 0) + 1
        