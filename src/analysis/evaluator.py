# src/analysis/evaluator.py
import logging
from pathlib import Path
from typing import Dict, Any, Optional
import yaml
import pandas as pd
import argparse
import sys

from src.analysis.aggregator import MetricsAggregator
from src.analysis.plotter import ResultsPlotter
from src.analysis.statistical_engine import StatEngine

logger = logging.getLogger("ThesisEvaluator")
logging.basicConfig(
    level=logging.INFO, 
    format='%(asctime)s [%(levelname)s] %(name)s: %(message)s'
)

class ThesisEvaluator:
    """
    The central orchestrator for automating the simulation analysis pipeline.
    
    This pipeline integrates data aggregation, statistical significance testing,
    and publication-ready plotting for rigorous federated learning evaluation.
    """
    
    def __init__(self, experiment_plan_path: str) -> None:
        """
        Initializes the evaluation pipeline using a specified experiment configuration.
        
        Args:
            experiment_plan_path (str): Path to the YAML file defining the experiment parameters.
        """
        self.plan_path = Path(experiment_plan_path)
        self.analysis_output_root = Path("analysis_outputs")
        self.analysis_output_root.mkdir(parents=True, exist_ok=True)
        
        self.aggregator = MetricsAggregator(time_rounding_decimals=1)
        self.plan = self._load_plan()
        self.results_root = Path(self.plan.get("output_root", "results"))

    def _load_plan(self) -> Dict[str, Any]:
        """
        Safely loads and parses the experiment YAML configuration.
        
        Returns:
            Dict[str, Any]: The parsed configuration dictionary.
            
        Raises:
            FileNotFoundError: If the specified configuration file does not exist.
        """
        if not self.plan_path.exists():
            logger.error(f"Experiment plan not found at: {self.plan_path}")
            raise FileNotFoundError(f"Missing configuration file: {self.plan_path}")
            
        with open(self.plan_path, 'r', encoding='utf-8') as file:
            return yaml.safe_load(file) or {}

    def run_pipeline(self) -> None:
        """
        Executes the complete automated analysis pipeline.
        
        Iterates through all experiments defined in the configuration, performs
        multi-seed aggregation, executes statistical tests, and generates comparative plots.
        """
        experiments = self.plan.get("experiments", [])
        if not experiments:
            logger.warning("No experiments defined in the execution plan.")
            return

        for exp in experiments:
            exp_name = exp.get("name", "unknown_experiment")
            logger.info(f"Starting automated analysis for experiment: '{exp_name}'")
            
            exp_output_dir = self.analysis_output_root / exp_name
            exp_output_dir.mkdir(parents=True, exist_ok=True)
            
            plotter = ResultsPlotter(output_dir=exp_output_dir)
            stat_engine = StatEngine(alpha=0.05)
            experiment_data: Dict[str, pd.DataFrame] = {}
            
            variations = exp.get("variations", [])
            for variation in variations:
                var_name = variation.get("tag", "unknown_variation")
                var_dir = self.results_root / exp_name / var_name
                
                logger.info(f"Processing variation: '{var_name}'")
                summary_df, detailed_df = self.aggregator.aggregate_variation(var_dir)
                
                if summary_df is not None and not summary_df.empty:
                    csv_output_path = exp_output_dir / f"{var_name}_aggregated.csv"
                    summary_df.to_csv(csv_output_path, index=False)
                    experiment_data[var_name] = summary_df
                    logger.debug(f"Aggregated data saved to {csv_output_path.name}")
                else:
                    logger.warning(f"No valid data aggregated for variation: '{var_name}'")
            
            self._execute_comparative_analysis(exp_name, experiment_data, plotter, stat_engine)

        logger.info("Evaluation pipeline execution completed successfully.")

    def _execute_comparative_analysis(
        self, 
        exp_name: str, 
        experiment_data: Dict[str, pd.DataFrame], 
        plotter: ResultsPlotter, 
        stat_engine: StatEngine
    ) -> None:
        """
        Dynamically evaluates all metrics generated by the active metric preset.
        
        Instead of hardcoding target metrics, this method dynamically inspects the 
        columns of the aggregated DataFrame (which are inherently dictated by the 
        active metric profile) and automatically generates plots and statistical 
        tests for each discovered metric.
        
        Args:
            exp_name (str): The name of the current experiment.
            experiment_data (Dict[str, pd.DataFrame]): Aggregated datasets for all variations.
            plotter (ResultsPlotter): Instance of the plotting engine.
            stat_engine (StatEngine): Instance of the statistical testing engine.
        """
        if len(experiment_data) < 2:
            logger.info(f"Insufficient variations to perform comparative analysis for '{exp_name}'.")
            return
            
        logger.info(f"Generating comparative analysis and plots for '{exp_name}'...")
        
        var_names = list(experiment_data.keys())
        baseline_name = var_names[0]
        baseline_df = experiment_data[baseline_name]
        
        # Dynamically discover target metrics from the DataFrame columns
        # We exclude structural columns ('clock', 'seed') and standard deviation columns ('_std')
        # because the plotter dynamically searches for the corresponding '_std' column given a mean.
        excluded_columns = {'clock', 'seed', 'node_id'}
        discovered_metrics = [
            col for col in baseline_df.columns 
            if col not in excluded_columns
            and not col.endswith('_std') 
            and not col.endswith('_count')
        ]
        
        if not discovered_metrics:
            logger.warning(f"No plottable metrics discovered for '{exp_name}'. Check your metric presets.")
            return

        logger.info(f"Discovered {len(discovered_metrics)} metrics from the active profile: {discovered_metrics}")
        
        for metric in discovered_metrics:
            logger.info(f"  -> Analyzing metric: {metric}")
            
            # Clean the metric name for professional plot titles (e.g., 'global_mean_accuracy_mean' -> 'Global Mean Accuracy')
            clean_metric_name = metric.replace('_mean', '').replace('_', ' ').title()
            
            # 1. Generate publication-ready plots dynamically
            plotter.plot_time_series_with_variance(
                data_dict=experiment_data,
                metric=metric,
                title=f"{clean_metric_name} - {exp_name.replace('_', ' ').title()}",
                xlabel="Simulation Time (s)",
                ylabel=clean_metric_name,
                filename=f"{metric}_comparison"
            )
            
            # 2. Compute statistical significance against the baseline
            for competitor_name in var_names[1:]:
                stat_engine.compute_significance(
                    df_a=baseline_df,
                    df_b=experiment_data[competitor_name],
                    metric=metric
                )
                
        output_dir = plotter.output_dir
        stat_engine.save_report(output_dir=output_dir, filename=f"{exp_name}_statistical_analysis.csv")
        self._write_final_table(exp_name, experiment_data, discovered_metrics, output_dir)

    def _write_final_table(
        self,
        exp_name: str,
        experiment_data: Dict[str, pd.DataFrame],
        metrics: list,
        output_dir: Path,
    ) -> None:
        """
        Emits the end-of-run value of every metric as one tidy `mean +/- std`
        table, one row per variation.

        The pipeline otherwise produces only time-series plots and a pairwise
        significance report, so assembling a results table meant reading the
        last row of ~30 per-variation CSVs by hand -- exactly the manual step
        that invites transcription errors into a paper. `_pretty` is emitted
        alongside the raw numbers so the values can be pasted into LaTeX as-is.
        See thesis-hub/docs/decisions.md, 2026-09-12.
        """
        rows = []
        for var_name, df in experiment_data.items():
            if df is None or df.empty:
                continue
            last = df.iloc[-1]
            row: Dict[str, Any] = {"variation": var_name, "clock": last.get("clock")}
            for metric in metrics:
                if metric not in df.columns:
                    continue
                base = metric[:-5] if metric.endswith("_mean") else metric
                mean = last.get(metric)
                std = last.get(f"{base}_std")
                n = last.get(f"{base}_count")
                row[metric] = mean
                row[f"{base}_std"] = std
                row[f"{base}_n"] = n
                if pd.notna(mean):
                    row[f"{base}_pretty"] = (
                        f"{mean:.2f} ± {std:.2f}" if pd.notna(std) else f"{mean:.2f}"
                    )

                # Mean over the whole run, alongside the final value.
                #
                # The final row is the right summary for a CONVERGED quantity
                # like accuracy, and the wrong one for a RATE.
                # `avg_cpu_utilization` is busy-time divided by the length of
                # the last reporting interval and is reset every tick, so its
                # final value describes only the last 30 seconds. Reading it
                # that way put IronForge at 9.8% here and 44.6% in the 40s
                # crash check - same protocol, same code, an order of magnitude
                # apart, purely from where the run happened to stop. The run
                # mean gives 51.9 +/- 0.3 against FARABI's 23.0 +/- 0.1: the
                # same conclusion the crash check suggested, but stable instead
                # of luck, and it is the number the paper's cost claim needs.
                # See thesis-hub/docs/decisions.md, 2026-09-12.
                series = df[metric].dropna()
                if not series.empty:
                    row[f"{base}_runmean"] = float(series.mean())
            rows.append(row)

        if not rows:
            logger.warning(f"No final-value rows to write for '{exp_name}'.")
            return

        out_path = output_dir / f"{exp_name}_final_table.csv"
        pd.DataFrame(rows).to_csv(out_path, index=False)
        logger.info(f"📋 Final results table written to: {out_path.name}")
        
if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="FARABI Automated Analysis Pipeline for Federated Learning.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter
    )
    
    parser.add_argument(
        "-p", "--plan",
        type=str,
        required=True,
        help="Relative or absolute path to the experiment YAML plan file."
    )
    
    args = parser.parse_args()
    
    try:
        evaluator = ThesisEvaluator(experiment_plan_path=args.plan)
        evaluator.run_pipeline()
    except FileNotFoundError as e:
        logger.critical(str(e))
        sys.exit(1)
    except Exception as e:
        logger.critical(f"An unexpected error occurred during execution: {e}")
        sys.exit(1)